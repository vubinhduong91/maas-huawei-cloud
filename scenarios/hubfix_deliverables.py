#!/usr/bin/env python3
"""Hub-fix Phase 4: build deliverables/hubfix/ from apisix/hubfix/patch.lua (the code the lab ran
and the unit tests check), so the hand-over copy can never drift from it.

  hubfix_patch.lua       the module, unchanged (for a Lua path: require("hubfix_patch"))
  pre-function.lua       the whole serverless-pre-function body: module inlined + handler
  route.apisix.yaml      APISIX standalone (config_provider: yaml) example route + upstream
  route.admin.json       the same route for the Admin API (PUT /apisix/admin/routes/<id>)

Placeholders the operator fills in: <MAAS_HOST>, <MAAS_PATH_PREFIX> (e.g. /anthropic),
<MAAS_AUTH_HEADER_VALUE> (e.g. "Bearer <key>"), GLM_MODEL at the top of the handler.
Usage: python3 scenarios/hubfix_deliverables.py [--glm-model glm-5.3] [--out deliverables/hubfix]
       [--upstream-host H --upstream-port P --upstream-scheme http --path-prefix /p --auth V]
       (the second line only for the lab test, scenarios/hubfix_deliverable_test.sh)
"""
import argparse
import json
from pathlib import Path

LAB = Path(__file__).resolve().parent.parent

HANDLER = '''local core = require("apisix.core")

-- The MaaS model name that requests for Claude Sonnet are sent to.
local GLM_MODEL = {glm}

return function(conf, ctx)
    -- APISIX may run rewrite-phase plugins twice for one request (again after an auth plugin
    -- found the consumer); the patch is idempotent, this only saves the second pass.
    if ctx.hubfix_done then
        return
    end
    ctx.hubfix_done = true
    local raw = core.request.get_body(nil, ctx)
    if not raw then
        return
    end
    local status, out, reason = hubfix.patch(raw, {{ decode = core.json.decode, glm_model = GLM_MODEL }})
    if status == "patched" then
        ngx.req.set_body_data(out)
    elseif status == "fallback" then
        -- The original body goes upstream unchanged; it is never re-encoded.
        core.log.warn("hubfix: forwarding the original body: ", reason)
    end
end
'''


def pre_function(glm):
    module = (LAB / "apisix" / "hubfix" / "patch.lua").read_text(encoding="utf-8").rstrip()
    head = ("-- serverless-pre-function (phase: rewrite) for the Claude Code -> MaaS route.\n"
            "-- Generated from apisix/hubfix/patch.lua by scenarios/hubfix_deliverables.py: edit that file.\n"
            "local hubfix = (function()\n")
    return head + module + "\nend)()\n\n" + HANDLER.format(glm=json.dumps(glm))


def route(fn, a):
    upstream = {"type": "roundrobin", "scheme": a.upstream_scheme, "pass_host": "node",
                "nodes": [{"host": a.upstream_host, "port": a.upstream_port, "weight": 1}],
                "timeout": {"connect": 10, "send": 600, "read": 600}}
    plugins = {
        "serverless-pre-function": {"phase": "rewrite", "functions": [fn]},
        "proxy-rewrite": {"regex_uri": ["^/v1/(.*)$", a.path_prefix + "/v1/$1"],
                          "headers": {"set": {"Authorization": a.auth}}},
    }
    return {"uris": ["/v1/messages", "/v1/messages/count_tokens"], "methods": ["POST"],
            "plugins": plugins, "upstream": upstream}


def yaml_scalar(v):
    return json.dumps(v)   # JSON strings / numbers are valid YAML scalars


def to_yaml(r, fn):
    up = r["upstream"]
    lines = ["# APISIX standalone example (conf/apisix.yaml, config_provider: yaml).",
             "# Generated by scenarios/hubfix_deliverables.py. Keep the Hub's own auth plugins on the route",
             "# (key-auth, consumers...) and put serverless-pre-function next to them.",
             "routes:",
             "  - id: claude-messages",
             "    uris: " + json.dumps(r["uris"]),
             "    methods: " + json.dumps(r["methods"]),
             "    upstream_id: maas",
             "    plugins:",
             "      serverless-pre-function:",
             "        phase: rewrite",
             "        functions:",
             "          - |"]
    lines += [("            " + l) if l.strip() else "" for l in fn.rstrip("\n").split("\n")]
    pr = r["plugins"]["proxy-rewrite"]
    lines += ["      proxy-rewrite:",
              "        regex_uri: " + json.dumps(pr["regex_uri"]),
              "        headers:",
              "          set:",
              "            Authorization: " + yaml_scalar(pr["headers"]["set"]["Authorization"]),
              "upstreams:",
              "  - id: maas",
              "    type: roundrobin",
              "    scheme: " + up["scheme"],
              "    pass_host: node",
              "    nodes:",
              "      - host: " + yaml_scalar(up["nodes"][0]["host"]),
              "        port: " + str(up["nodes"][0]["port"]),
              "        weight: 1",
              "    timeout:",
              "      connect: 10",
              "      send: 600",
              "      read: 600",
              "#END"]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--glm-model", default="glm-5.3")
    ap.add_argument("--out", default=str(LAB / "deliverables" / "hubfix"))
    ap.add_argument("--upstream-host", default="<MAAS_HOST>")
    ap.add_argument("--upstream-port", type=int, default=443)
    ap.add_argument("--upstream-scheme", default="https")
    ap.add_argument("--path-prefix", default="<MAAS_PATH_PREFIX>")
    ap.add_argument("--auth", default="<MAAS_AUTH_HEADER_VALUE>")
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    fn = pre_function(a.glm_model)
    r = route(fn, a)
    def write(name, text):   # LF endings on every OS (python 3.9: no newline= on write_text)
        with open(out / name, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)

    write("hubfix_patch.lua", (LAB / "apisix" / "hubfix" / "patch.lua").read_text(encoding="utf-8"))
    write("pre-function.lua", fn)
    write("route.apisix.yaml", to_yaml(r, fn))
    write("route.admin.json", json.dumps(r, indent=2, ensure_ascii=False) + "\n")
    print(f"wrote {out}: hubfix_patch.lua, pre-function.lua, route.apisix.yaml, route.admin.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
